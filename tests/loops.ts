// Laços (Loops)
// For:
for (let i: number = 0; i < 5; i++) {
    console.log(i);
}

// While:
let contador: number = 0;

while (contador < 5) {
    console.log(contador);
    contador++;
}

// For...of:
let frutas: string[] = ["Maçã", "Banana", "Uva"];

for (let fruta of frutas) {
    console.log(fruta);
}